#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const options = parseArgs(process.argv.slice(2))
const startedAt = new Date()
const migrationRoot = path.resolve(
  options.outputDir ||
    path.join('.openclaude-data', 'migrations', 'openrag-to-lightrag', timestamp(startedAt)),
)

await mkdir(migrationRoot, { recursive: true })

const sourceExport = options.sourceJson
  ? JSON.parse(await readFile(path.resolve(options.sourceJson), 'utf8'))
  : exportOpenRAGIndex(options)

const hits = normalizeHits(sourceExport)
const documents = rebuildDocuments(hits)
if (documents.length === 0) {
  throw new Error('OpenRAG export contained no documents; refusing to report a successful migration')
}

await writeJson(path.join(migrationRoot, 'openrag-export.json'), sourceExport)
await writeJson(path.join(migrationRoot, 'lightrag-payload.json'), {
  generated_at: startedAt.toISOString(),
  source: 'OpenRAG OpenSearch index',
  note: [
    'Embeddings are intentionally regenerated by LightRAG; the original Docker volume is not deleted.',
    'OpenRAG metadata is retained in this manifest and the immutable source export, while only original document text is indexed to keep technical metadata out of the knowledge graph.',
  ].join(' '),
  documents,
})

const report = {
  started_at: startedAt.toISOString(),
  source_container: options.openSearchContainer,
  source_index: options.openSearchIndex,
  source_chunks: hits.length,
  reconstructed_documents: documents.length,
  source_volume_preserved: true,
  output_directory: migrationRoot,
  submissions: [],
  verification: {},
}

if (!options.exportOnly) {
  await waitForLightRAG(options)
  for (const document of documents) {
    const submission = await submitDocument(document, options)
    report.submissions.push(submission)
    await writeJson(path.join(migrationRoot, 'report.json'), report)
  }

  for (const submission of report.submissions) {
    if (!submission.track_id) continue
    submission.final_status = await waitForTrack(submission.track_id, options)
    await writeJson(path.join(migrationRoot, 'report.json'), report)
  }

  const failed = report.submissions.filter(item => {
    if (item.state === 'already_present') return false
    const summary = item.final_status?.status_summary || {}
    return Object.entries(summary).some(([status, count]) =>
      String(status).toUpperCase().includes('FAILED') && Number(count) > 0,
    )
  })
  if (failed.length > 0) {
    throw new Error(`${failed.length} LightRAG document(s) failed during indexing; OpenRAG remains untouched`)
  }

  const listing = await lightRAGJson('/documents', {}, options)
  const indexedCount = countDocuments(listing)
  const indexedSources = listDocumentSources(listing)
  const missingSources = documents
    .map(document => document.file_source)
    .filter(fileSource => !indexedSources.has(fileSource))
  report.verification.document_status_count = indexedCount
  report.verification.expected_documents = documents.length
  report.verification.migrated_file_sources = documents.length - missingSources.length
  report.verification.missing_file_sources = missingSources
  report.verification.status_count_ok = indexedCount >= documents.length
  report.verification.exact_sources_ok = missingSources.length === 0

  const sampleQuery = documents[0].text.replace(/\s+/gu, ' ').trim().slice(0, 240)
  if (sampleQuery.length >= 3) {
    const query = await lightRAGJson('/query', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        query: sampleQuery,
        mode: 'naive',
        only_need_context: true,
        include_references: true,
        include_chunk_content: true,
      }),
    }, options)
    report.verification.retrieval_nonempty = Boolean(
      String(query?.response || '').trim() || (Array.isArray(query?.references) && query.references.length > 0),
    )
  }

  report.completed_at = new Date().toISOString()
  report.ok = report.verification.status_count_ok
    && report.verification.exact_sources_ok
    && report.verification.retrieval_nonempty !== false
  await writeJson(path.join(migrationRoot, 'report.json'), report)
  if (!report.ok) {
    throw new Error('LightRAG verification did not confirm all migrated documents; OpenRAG remains untouched')
  }
} else {
  report.completed_at = new Date().toISOString()
  report.ok = true
  report.export_only = true
  await writeJson(path.join(migrationRoot, 'report.json'), report)
}

console.log(JSON.stringify({
  ok: report.ok,
  source_chunks: report.source_chunks,
  reconstructed_documents: report.reconstructed_documents,
  migrated_documents: report.submissions.filter(item => item.state === 'submitted').length,
  already_present: report.submissions.filter(item => item.state === 'already_present').length,
  backup: migrationRoot,
}, null, 2))

function parseArgs(args) {
  const result = {
    openSearchContainer: process.env.OPENRAG_OPENSEARCH_CONTAINER || 'os',
    openSearchIndex: process.env.OPENRAG_OPENSEARCH_INDEX || 'documents',
    lightRAGUrl: (process.env.LIGHTRAG_URL || 'http://127.0.0.1:9621').replace(/\/+$/u, ''),
    lightRAGApiKey: process.env.LIGHTRAG_API_KEY || '',
    waitTimeoutMs: Number(process.env.LIGHTRAG_MIGRATION_TIMEOUT_MS || 30 * 60 * 1000),
    pollMs: Number(process.env.LIGHTRAG_MIGRATION_POLL_MS || 5000),
    exportOnly: false,
  }
  for (let index = 0; index < args.length; index += 1) {
    const name = args[index]
    const value = args[index + 1]
    if (name === '--source-json') { result.sourceJson = requiredValue(name, value); index += 1 }
    else if (name === '--output-dir') { result.outputDir = requiredValue(name, value); index += 1 }
    else if (name === '--opensearch-container') { result.openSearchContainer = requiredValue(name, value); index += 1 }
    else if (name === '--opensearch-index') { result.openSearchIndex = requiredValue(name, value); index += 1 }
    else if (name === '--lightrag-url') { result.lightRAGUrl = requiredValue(name, value).replace(/\/+$/u, ''); index += 1 }
    else if (name === '--lightrag-api-key') { result.lightRAGApiKey = requiredValue(name, value); index += 1 }
    else if (name === '--wait-timeout-ms') { result.waitTimeoutMs = Number(requiredValue(name, value)); index += 1 }
    else if (name === '--poll-ms') { result.pollMs = Number(requiredValue(name, value)); index += 1 }
    else if (name === '--export-only') result.exportOnly = true
    else throw new Error(`Unknown or incomplete argument: ${name}`)
  }
  if (!/^[A-Za-z0-9_.-]+$/u.test(result.openSearchContainer)) {
    throw new Error('Invalid OpenSearch container name')
  }
  if (!/^[A-Za-z0-9_.-]+$/u.test(result.openSearchIndex)) {
    throw new Error('Invalid OpenSearch index name')
  }
  if (!Number.isFinite(result.waitTimeoutMs) || result.waitTimeoutMs < 1000) {
    throw new Error('wait timeout must be at least 1000ms')
  }
  if (!Number.isFinite(result.pollMs) || result.pollMs < 100 || result.pollMs > result.waitTimeoutMs) {
    throw new Error('poll interval must be between 100ms and the wait timeout')
  }
  return result
}

function requiredValue(name, value) {
  if (!value || value.startsWith('--')) throw new Error(`Missing value for ${name}`)
  return value
}

function exportOpenRAGIndex(config) {
  const search = openSearchRequest(
    config,
    `${config.openSearchIndex}/_search?scroll=2m`,
    {
      size: 500,
      sort: ['_doc'],
      query: { match_all: {} },
      _source: { excludes: ['chunk_embedding_*'] },
    },
  )
  const hits = [...(search.hits?.hits || [])]
  let scrollId = search._scroll_id
  while (scrollId) {
    const page = openSearchRequest(config, '_search/scroll', { scroll: '2m', scroll_id: scrollId })
    const pageHits = page.hits?.hits || []
    if (pageHits.length === 0) break
    hits.push(...pageHits)
    scrollId = page._scroll_id
  }

  const mapping = openSearchRequest(config, `${config.openSearchIndex}/_mapping`)
  const settings = openSearchRequest(config, `${config.openSearchIndex}/_settings`)
  return {
    exported_at: new Date().toISOString(),
    source_container: config.openSearchContainer,
    source_index: config.openSearchIndex,
    embeddings_exported: false,
    embeddings_note: 'Original embeddings stay in the preserved OpenSearch Docker volume; LightRAG regenerates its own vectors.',
    mapping,
    settings,
    hits,
  }
}

function openSearchRequest(config, endpoint, body) {
  const url = `https://127.0.0.1:9200/${endpoint}`
  const shellCommand = body
    ? `curl -ksS -u "admin:$OPENSEARCH_INITIAL_ADMIN_PASSWORD" -H "Content-Type: application/json" --data-binary @- "${url}"`
    : `curl -ksS -u "admin:$OPENSEARCH_INITIAL_ADMIN_PASSWORD" "${url}"`
  const child = spawnSync(
    'docker',
    ['exec', ...(body ? ['-i'] : []), config.openSearchContainer, 'sh', '-lc', shellCommand],
    {
      encoding: 'utf8',
      input: body ? JSON.stringify(body) : undefined,
      maxBuffer: 256 * 1024 * 1024,
      windowsHide: true,
    },
  )
  if (child.status !== 0) {
    throw new Error(`OpenSearch export failed: ${String(child.stderr || child.error || '').trim()}`)
  }
  try {
    const data = JSON.parse(child.stdout)
    if (data?.error) throw new Error(JSON.stringify(data.error))
    return data
  } catch (error) {
    throw new Error(`OpenSearch returned invalid JSON: ${error.message}`)
  }
}

function normalizeHits(sourceExport) {
  if (Array.isArray(sourceExport.hits)) return sourceExport.hits
  if (Array.isArray(sourceExport.hits?.hits)) return sourceExport.hits.hits
  if (Array.isArray(sourceExport)) return sourceExport
  return []
}

function rebuildDocuments(hits) {
  const groups = new Map()
  for (const hit of hits) {
    const source = hit._source || hit
    const text = String(source.text || '').trim()
    if (!text) continue
    const key = String(source.document_id || source.filename || hit._id || hash(text)).trim()
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push({ id: hit._id || key, source, text })
  }

  return [...groups.entries()].map(([documentId, chunks]) => {
    chunks.sort((left, right) => comparePage(left.source.page, right.source.page) || left.id.localeCompare(right.id))
    const first = chunks[0].source
    const originalFilename = String(first.filename || `${documentId}.txt`)
    const uniqueTexts = [...new Set(chunks.map(chunk => chunk.text))]
    const metadata = {
      migrated_from: 'OpenRAG',
      document_id: documentId,
      filename: originalFilename,
      source_url: first.source_url || null,
      connector_type: first.connector_type || null,
      mimetype: first.mimetype || null,
      owner: first.owner || first.owner_name || null,
      created_time: first.created_time || null,
      modified_time: first.modified_time || null,
      indexed_time: first.indexed_time || null,
      openrag_metadata: first.metadata || null,
      source_chunk_count: chunks.length,
    }
    return {
      document_id: documentId,
      file_source: migratedFilename(originalFilename, documentId),
      metadata,
      text: uniqueTexts.join('\n\n'),
    }
  })
}

function migratedFilename(filename, documentId) {
  const rawName = filename.split(/[\\/]/u).pop() || 'document.txt'
  const cleaned = rawName.replace(/[<>:"|?*\u0000-\u001f]/gu, '_').trim() || 'document.txt'
  const digest = hash(documentId).slice(0, 10)
  const extension = path.extname(cleaned)
  const stem = (extension ? cleaned.slice(0, -extension.length) : cleaned).slice(0, 180)
  return `${stem}__openrag_${digest}${extension || '.txt'}`
}

function comparePage(left, right) {
  const leftNumber = Number(left)
  const rightNumber = Number(right)
  if (Number.isFinite(leftNumber) && Number.isFinite(rightNumber)) return leftNumber - rightNumber
  return String(left || '').localeCompare(String(right || ''))
}

async function submitDocument(document, config) {
  try {
    const response = await lightRAGJson('/documents/text', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text: document.text, file_source: document.file_source }),
    }, config)
    return {
      document_id: document.document_id,
      file_source: document.file_source,
      state: 'submitted',
      track_id: response.track_id,
    }
  } catch (error) {
    if (error.status === 409) {
      return {
        document_id: document.document_id,
        file_source: document.file_source,
        state: 'already_present',
      }
    }
    throw error
  }
}

async function waitForLightRAG(config) {
  const deadline = Date.now() + Math.min(config.waitTimeoutMs, 5 * 60 * 1000)
  let lastError
  while (Date.now() < deadline) {
    try {
      await lightRAGJson('/health', {}, config)
      return
    } catch (error) {
      lastError = error
      await delay(Math.min(config.pollMs, 3000))
    }
  }
  throw new Error(`LightRAG did not become healthy: ${lastError?.message || 'timeout'}`)
}

async function waitForTrack(trackId, config) {
  const deadline = Date.now() + config.waitTimeoutMs
  let latest
  while (Date.now() < deadline) {
    latest = await lightRAGJson(`/documents/track_status/${encodeURIComponent(trackId)}`, {}, config)
    const summary = latest?.status_summary || {}
    const statuses = Object.entries(summary)
    const total = Number(latest?.total_count || 0)
    const terminalCount = statuses.reduce((sum, [status, count]) => {
      const normalized = String(status).toUpperCase().split('.').pop()
      return sum + (normalized === 'PROCESSED' || normalized === 'FAILED' ? Number(count) : 0)
    }, 0)
    if (total > 0 && terminalCount >= total) return latest
    await delay(config.pollMs)
  }
  throw new Error(`Timed out waiting for LightRAG track ${trackId}; last status: ${JSON.stringify(latest?.status_summary || {})}`)
}

async function lightRAGJson(endpoint, init, config) {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), 120000)
  try {
    const response = await fetch(`${config.lightRAGUrl}${endpoint}`, {
      ...init,
      headers: {
        ...(config.lightRAGApiKey ? { 'X-API-Key': config.lightRAGApiKey } : {}),
        ...(init.headers || {}),
      },
      signal: controller.signal,
    })
    const body = await response.text()
    let data
    try { data = body ? JSON.parse(body) : null } catch { data = body }
    if (!response.ok) {
      const error = new Error(`LightRAG ${response.status}: ${JSON.stringify(data)}`)
      error.status = response.status
      throw error
    }
    return data
  } finally {
    clearTimeout(timer)
  }
}

function countDocuments(listing) {
  const statuses = listing?.statuses || listing || {}
  return Object.values(statuses).reduce((sum, value) => sum + (Array.isArray(value) ? value.length : 0), 0)
}

function listDocumentSources(listing) {
  const statuses = listing?.statuses || listing || {}
  const sources = Object.values(statuses)
    .flatMap(value => Array.isArray(value) ? value : [])
    .map(document => String(document?.file_path || document?.file_source || '').trim())
    .filter(Boolean)
  return new Set(sources)
}

function hash(value) {
  return createHash('sha256').update(String(value)).digest('hex')
}

function timestamp(date) {
  return date.toISOString().replace(/[:.]/gu, '-').replace('T', '_').replace('Z', '')
}

async function writeJson(filename, value) {
  await writeFile(filename, `${JSON.stringify(value, null, 2)}\n`, 'utf8')
}

async function delay(ms) {
  await new Promise(resolvePromise => setTimeout(resolvePromise, ms))
}
